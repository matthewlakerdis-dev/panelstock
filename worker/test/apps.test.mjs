import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
test('mobile bundle parses, uses individual sessions and excludes voided jobs',()=>{
 const html=fs.readFileSync(new URL('../../index.html',import.meta.url),'utf8');
 for(const match of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g))if(match[1].trim())new vm.Script(match[1]);
 assert.ok(html.includes('panelstock-client.js'));
 assert.ok(!html.includes('BAKED_SHARED_SECRET'));
 assert.ok(!html.includes('.slice(0, 800)'));
 assert.match(html,/ResizeObserver loop \(\?:limit exceeded\|completed with undelivered notifications\)/);
 assert.match(html,/ResizeObserver loop \(\?:limit exceeded\|completed with undelivered notifications\)/);
 const dispatch=html.slice(html.indexOf('function DispatchTab'),html.indexOf('function DamageTab'));
 assert.match(dispatch,/ItemPicker[^\n]+sortLikeSoh: true/);
 assert.match(html,/function ScheduleTab\(\)/);
 const cncTab=html.slice(html.indexOf('function CncTab('),html.indexOf('function SettingsTab('));
 assert.match(cncTab,/children: "Complete sheet"/);
 assert.doesNotMatch(cncTab,/children: "Complete panel"/);
 assert.match(html,/function ProfilePhotoSettings\(\)/);
 assert.match(html,/const cropPhoto=/);
 assert.match(html,/children:"Adjust photo"/);
 assert.match(html,/onPointerDown:pointerDown/);
 assert.match(html,/onWheel:event/);
 assert.match(html,/Drag to reposition\. Pinch or scroll to zoom\./);
 assert.match(html,/id: "profile", label: "Profile"/);
 assert.match(html,/tab === "profile"/);
 assert.match(html,/\/profile/);
 assert.match(html,/function ScheduleCalendarIcon/);
 assert.match(fs.readFileSync(new URL('../src/schedule-display.js',import.meta.url),'utf8'),/Read-only TV display/);
 assert.match(fs.readFileSync(new URL('../src/schedule-display.js',import.meta.url),'utf8'),/timeline-head/);
 assert.match(fs.readFileSync(new URL('../src/schedule-display.js',import.meta.url),'utf8'),/\.timeline\{width:100%;min-width:0\}/);
 assert.match(fs.readFileSync(new URL('../src/schedule-display.js',import.meta.url),'utf8'),/grid-template-columns:clamp\(118px,16vw,190px\) minmax\(0,1fr\)/);
 assert.doesNotMatch(fs.readFileSync(new URL('../src/schedule-display.js',import.meta.url),'utf8'),/min-width:1050px/);
 assert.match(fs.readFileSync(new URL('../src/schedule-display.js',import.meta.url),'utf8'),/meta name="color-scheme" content="only light"/);
 assert.match(fs.readFileSync(new URL('../src/schedule-display.js',import.meta.url),'utf8'),/html\{color-scheme:only light\}/);
 assert.doesNotMatch(fs.readFileSync(new URL('../src/schedule-display.js',import.meta.url),'utf8'),/id="clock"/);
 assert.match(fs.readFileSync(new URL('../src/schedule-display.js',import.meta.url),'utf8'),/<h1 id="date"><\/h1>/);
 assert.match(html,/Read-only project schedule/);
 assert.match(html,/BAKED_WORKER_URL\+"\/schedule"/);
 assert.match(html,/My schedule/);
 assert.match(html,/All schedules/);
 assert.match(html,/assignedUsername===viewer/);
 assert.match(html,/id: "transfer", label: "Convert"/);
 assert.match(html,/tab === "transfer"/);
 assert.match(html,/primaryIds=new Set\(\["stock","receive","damage","cnc","schedule"\]\)/);
 assert.doesNotMatch(html,/children: "Register"/);
 assert.doesNotMatch(fs.readFileSync(new URL('../../site/app.js',import.meta.url),'utf8'),/data-mode="register"/);
 const filter=html.match(/const dispatches = transactions.filter\(([^;]+)\);/)[1];
 const result=vm.runInNewContext(`transactions.filter(${filter})`,{transactions:[{type:'dispatch',qty:2},{type:'dispatch',qty:5,voided:true}]});
 assert.equal(result.length,1);assert.equal(result[0].qty,2);
});

