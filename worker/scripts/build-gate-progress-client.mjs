import fs from 'node:fs';
const input=new URL('../src/gate-progress-client.js',import.meta.url),output=new URL('../generated/gate-progress-client.js',import.meta.url);
const source=fs.readFileSync(input,'utf8').replace(/^export function gateProgressApp/, 'function gateProgressApp')+'\ngateProgressApp();\n';
const built='// Generated by scripts/build-gate-progress-client.mjs.\nexport const gateProgressClient='+JSON.stringify(source)+';\n';
if(process.argv.includes('--check')){if(!fs.existsSync(output)||fs.readFileSync(output,'utf8')!==built)throw Error('Gate progress client is out of date. Run node scripts/build-gate-progress-client.mjs.');}
else fs.writeFileSync(output,built);
