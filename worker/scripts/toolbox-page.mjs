import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=fs.readFileSync(path.join(root,'src/toolbox.js'),'utf8');
const start=source.indexOf('export function toolboxContent('),end=source.indexOf('\nfunction date(',start);
if(start<0||end<0)throw Error('Could not locate shared toolbox signature content function');
const contentFunction=source.slice(start,end).replace(/^export /,'');
const template=fs.readFileSync(path.join(root,'templates/toolbox.html'),'utf8');
if(template.split('__TOOLBOX_CONTENT_FUNCTION__').length!==2)throw Error('Toolbox template needs exactly one content function marker');
const html=template.replace('__TOOLBOX_CONTENT_FUNCTION__',contentFunction);
const output='// Generated by scripts/toolbox-page.mjs from templates/toolbox.html and toolbox.js.\nexport function buildToolboxPage(){return '+JSON.stringify(html)+';}\n';
const target=path.join(root,'src/toolbox-page.js');
if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output)throw Error('Toolbox page is out of date. Run node scripts/toolbox-page.mjs.');console.log('Toolbox page matches template and signature content function.');}
else fs.writeFileSync(target,output);
